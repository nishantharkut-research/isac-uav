"""Plot generated Figure 4 histories with confidence intervals and evidence."""

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from scipy.stats import t

from experiment_protocol import atomic_write_json
from paper_reference import load_paper_references
from source_integrity import source_tree_digest
from validate_results import (
    METHOD_ORDER,
    result_payload_digest,
    validate_baseline_result,
)


def _causal_smooth(values, window):
    values = np.asarray(values, dtype=float)
    result = np.empty_like(values)
    for index in range(values.size):
        result[index] = np.mean(values[max(0, index - window + 1):index + 1])
    return result


def build_fig4_plot_data(summary, smoothing_window=20):
    """Build plotted arrays only from complete raw per-seed histories."""
    smoothing_window = int(smoothing_window)
    if smoothing_window <= 0:
        raise ValueError("smoothing window must be positive")
    protocol = summary.get("figure4_protocol")
    expected_protocol = {
        "raw_episode_count": 1500,
        "plot_x_start": 0,
        "plot_x_end": 1400,
        "plot_interval": 100,
        "acceptance_smoothing_window": 20,
    }
    if summary.get("episodes") != 1500 or protocol != expected_protocol:
        raise ValueError("Summary is not the declared Figure 4 protocol")
    seeds = summary.get("seeds")
    records = summary.get("seed_records")
    if (
        not isinstance(seeds, list)
        or len(seeds) < 5
        or len(set(seeds)) != len(seeds)
        or not isinstance(records, list)
        or len(records) != len(seeds)
    ):
        raise ValueError("Figure 4 requires complete records for five seeds")
    records_by_seed = {record.get("seed"): record for record in records}
    if set(records_by_seed) != set(seeds):
        raise ValueError("Figure 4 seed records do not match the declared seeds")
    x = np.arange(0, 1500, 100, dtype=int)
    curves, ci_low, ci_high, raw_histories = {}, {}, {}, {}
    for method in METHOD_ORDER:
        histories = []
        for seed in seeds:
            try:
                history = np.asarray(
                    records_by_seed[seed]["methods"][method]["training"]["comm_rates"],
                    dtype=float,
                )
            except (KeyError, TypeError, ValueError) as error:
                raise ValueError(f"Missing raw history for {method}, seed {seed}") from error
            if history.shape != (1500,) or not np.all(np.isfinite(history)):
                raise ValueError(f"Invalid raw history for {method}, seed {seed}")
            histories.append(history)
        raw = np.stack(histories)
        smoothed = np.stack([
            _causal_smooth(history, smoothing_window) for history in raw
        ])[:, x]
        mean = np.mean(smoothed, axis=0)
        standard_error = np.std(smoothed, axis=0, ddof=1) / np.sqrt(len(seeds))
        half_width = t.ppf(0.975, len(seeds) - 1) * standard_error
        curves[method] = mean.tolist()
        ci_low[method] = (mean - half_width).tolist()
        ci_high[method] = (mean + half_width).tolist()
        raw_histories[method] = raw.tolist()
    return {
        "x": x.tolist(),
        "curves": curves,
        "ci95_low": ci_low,
        "ci95_high": ci_high,
        "raw_histories": raw_histories,
        "smoothing_window": smoothing_window,
    }


def _read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline-summary", required=True)
    parser.add_argument(
        "--reference", default="references/paper_reference_curves.json"
    )
    parser.add_argument("--output", required=True)
    parser.add_argument("--smoothing-window", type=int, default=20)
    args = parser.parse_args(argv)

    summary = _read_json(args.baseline_summary)
    references = load_paper_references(args.reference)
    validation = validate_baseline_result(
        summary,
        references,
        result_directory=Path(args.baseline_summary).resolve().parent,
        verify_files=True,
    )
    current_digest = source_tree_digest()
    if summary.get("source_tree_digest") != current_digest:
        raise ValueError("Baseline summary was generated by a different source tree")
    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    if any(output.iterdir()):
        raise ValueError("Figure output directory must be empty")

    data = build_fig4_plot_data(summary, args.smoothing_window)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    styles = {
        "DTL-pCSI": ("#1677b8", "o"),
        "DTL-WFB": ("#28913b", "^"),
        "DTL-iCSI": ("#ed7d19", "D"),
        "DDPG": ("#c83232", "s"),
    }
    figure, axis = plt.subplots(figsize=(8.2, 5.2))
    x = np.asarray(data["x"])
    for method in METHOD_ORDER:
        color, marker = styles[method]
        mean = np.asarray(data["curves"][method])
        axis.plot(x, mean, color=color, marker=marker, linewidth=1.8,
                  markersize=4.5, label=method)
        axis.fill_between(
            x,
            data["ci95_low"][method],
            data["ci95_high"][method],
            color=color,
            alpha=0.12,
            linewidth=0,
        )
    axis.set_xlabel("Number of Episodes")
    axis.set_ylabel("Communication Sum Rate (bits/s/Hz)")
    axis.set_title("Fig. 4 - Training Reward vs Episodes")
    axis.grid(True, alpha=0.25)
    axis.legend()
    figure.tight_layout()
    image_path = output / "fig4_rewards_vs_episodes.png"
    figure.savefig(image_path, dpi=220, bbox_inches="tight")
    plt.close(figure)

    arrays = {"x": data["x"]}
    for method in METHOD_ORDER:
        arrays[method] = data["curves"][method]
        arrays[f"{method}_ci95_low"] = data["ci95_low"][method]
        arrays[f"{method}_ci95_high"] = data["ci95_high"][method]
    evidence = {
        "schema_version": 1,
        "kind": "generated_result_evidence",
        "figure": 4,
        "source_tree_digest": current_digest,
        "profile_digest": summary["profile_digest"],
        "physical_configuration_fingerprint": summary[
            "physical_configuration_fingerprint"
        ],
        "power_hypothesis_id": summary["power_hypothesis_id"],
        "noise_hypothesis_id": summary["noise_hypothesis_id"],
        "dtl_transfer_mode": summary["dtl_transfer_mode"],
        "dtl_transfer_schedule_id": summary["dtl_transfer_schedule_id"],
        "wfb_hypothesis_id": summary["wfb_hypothesis_id"],
        "ddpg_comparator_csi_hypothesis_id": summary[
            "ddpg_comparator_csi_hypothesis_id"
        ],
        "los_probability_hypothesis_id": summary[
            "los_probability_hypothesis_id"
        ],
        "channel_coherence_hypothesis_id": summary[
            "channel_coherence_hypothesis_id"
        ],
        "cross_function_interference_hypothesis_id": summary[
            "cross_function_interference_hypothesis_id"
        ],
        "baseline_summary_sha256": result_payload_digest(summary),
        "paper_reference_sha256": validation["paper_reference_sha256"],
        "seeds": summary["seeds"],
        "units": {"x": "episodes", "reward": "bits/s/Hz"},
        "arrays": arrays,
        "x": data["x"],
        "curves": data["curves"],
        "raw_training_histories": data["raw_histories"],
        "smoothing": {
            "purpose": "visualization_only",
            "method": "causal_moving_average",
            "window": data["smoothing_window"],
        },
        "acceptance_uses_raw_histories": True,
        "feasibility_rate": summary["feasibility_rate"],
    }
    evidence_path = atomic_write_json(output / "fig4_data.json", evidence)
    validation_path = atomic_write_json(
        output / "baseline_validation.json", validation
    )
    manifest = {
        "schema_version": 1,
        "kind": "generated_result_manifest",
        "baseline_summary_sha256": result_payload_digest(summary),
        "paper_reference_sha256": validation["paper_reference_sha256"],
        "validation": validation_path.name,
        "validation_sha256": _sha256(validation_path),
        "artifacts": [{
            "image": image_path.name,
            "evidence": evidence_path.name,
            "image_sha256": _sha256(image_path),
            "evidence_sha256": _sha256(evidence_path),
        }],
    }
    atomic_write_json(output / "result_manifest.json", manifest)
    return 0 if validation["overall_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
